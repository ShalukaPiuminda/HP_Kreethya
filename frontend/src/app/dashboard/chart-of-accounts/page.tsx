'use client';

import { useCallback, useEffect, useState } from 'react';
import { Landmark, Pencil, Plus, Trash2 } from 'lucide-react';
import {
  LoadingTableRow,
  OperationActions,
  OperationField,
  OperationHeader,
  OperationMetric,
  OperationModal,
  OperationNotice,
  StatusPill,
} from '@/components/operation-ui';
import { api, getApiErrorMessage } from '@/lib/api';
import { type FinanceOptions, type FinanceSummary, type LedgerAccount, financeMoney } from '@/lib/finance';
import { useAuth } from '@/lib/auth-context';
import { SearchSelect } from '@/components/search-select';

export default function ChartOfAccountsPage() {
  const { hasPermission } = useAuth();
  const [accounts, setAccounts] = useState<LedgerAccount[]>([]);
  const [options, setOptions] = useState<FinanceOptions | null>(null);
  const [summary, setSummary] = useState<FinanceSummary | null>(null);
  const [editing, setEditing] = useState<LedgerAccount | 'new' | null>(null);
  const [loading, setLoading] = useState(true);
  const [notice, setNotice] = useState<{ type: 'success' | 'error'; text: string } | null>(null);

  const load = useCallback(async () => {
    setLoading(true);
    try {
      const [accountResponse, optionResponse, summaryResponse] = await Promise.all([
        api.getAll<LedgerAccount>('/v1/accounts'),
        api.get<FinanceOptions>('/v1/finance/options'),
        api.get<FinanceSummary>('/v1/finance/summary'),
      ]);
      setAccounts(accountResponse.data || []);
      setOptions(optionResponse.data || null);
      setSummary(summaryResponse.data || null);
    } catch (error) {
      setNotice({ type: 'error', text: getApiErrorMessage(error) });
    } finally {
      setLoading(false);
    }
  }, []);

  useEffect(() => {
    const timer = window.setTimeout(load, 0);
    return () => window.clearTimeout(timer);
  }, [load]);

  async function remove(account: LedgerAccount) {
    if (!window.confirm(`Delete ${account.code} · ${account.description}?`)) return;
    try {
      await api.delete(`/v1/accounts/${account.id}`);
      setNotice({ type: 'success', text: 'Account deleted.' });
      load();
    } catch (error) {
      setNotice({ type: 'error', text: getApiErrorMessage(error) });
    }
  }

  return (
    <div className="space-y-6">
      <OperationHeader eyebrow="General Ledger" title="Chart of Accounts" description="Maintain the branch ledger structure and inspect live balances generated by operational transactions." icon={Landmark} actions={hasPermission('accounts', 'can_create') ? <button onClick={() => setEditing('new')} className="inline-flex items-center gap-2 rounded-xl bg-indigo-600 px-4 py-2.5 text-sm font-semibold text-white"><Plus className="h-4 w-4" /> New account</button> : null} />
      {notice && <OperationNotice type={notice.type}>{notice.text}</OperationNotice>}
      <section className="grid gap-4 sm:grid-cols-2 xl:grid-cols-4"><OperationMetric label="Cash balance" value={financeMoney(summary?.cash_balance)} tone="emerald" /><OperationMetric label="Bank balance" value={financeMoney(summary?.bank_balance)} tone="indigo" /><OperationMetric label="Receivables" value={financeMoney(summary?.receivables)} tone="amber" /><OperationMetric label="Trial balance difference" value={financeMoney(summary?.trial_balance_difference)} tone={summary?.trial_balance_difference ? 'rose' : 'emerald'} /></section>
      <section className="overflow-hidden rounded-2xl border border-slate-200 bg-white shadow-sm">
        <div className="content-scrollbar overflow-x-auto">
          <table className="w-full text-left text-sm">
            <thead className="bg-slate-50 text-xs uppercase tracking-wide text-slate-500"><tr><th className="px-5 py-3">Code</th><th className="px-5 py-3">Account</th><th className="px-5 py-3">Classification</th><th className="px-5 py-3">Balance</th><th className="px-5 py-3">Status</th><th className="px-5 py-3 text-right">Actions</th></tr></thead>
            <tbody className="divide-y divide-slate-100">
              {loading ? <LoadingTableRow columns={6} label="Loading accounts..." /> : accounts.map((account) => <tr key={account.id}><td className="px-5 py-4 font-mono font-semibold text-indigo-700">{account.code}</td><td className="px-5 py-4 font-medium">{account.description}</td><td className="px-5 py-4"><div>{account.type?.name}</div><div className="text-xs text-slate-500">{account.type?.category?.name}</div></td><td className="px-5 py-4 font-semibold">{financeMoney(account.balance)}</td><td className="px-5 py-4"><StatusPill status={account.is_active ? 'active' : 'inactive'} /></td><td className="px-5 py-4 text-right"><div className="inline-flex gap-1">{hasPermission('accounts', 'can_update') && <button onClick={() => setEditing(account)} className="rounded-lg p-2 text-indigo-600 hover:bg-indigo-50"><Pencil className="h-4 w-4" /></button>}{hasPermission('accounts', 'can_delete') && <button onClick={() => remove(account)} className="rounded-lg p-2 text-rose-600 hover:bg-rose-50"><Trash2 className="h-4 w-4" /></button>}</div></td></tr>)}
            </tbody>
          </table>
        </div>
      </section>
      {editing && options && <AccountModal account={editing === 'new' ? null : editing} options={options} onClose={() => setEditing(null)} onSaved={() => { setEditing(null); setNotice({ type: 'success', text: 'Account saved.' }); load(); }} />}
    </div>
  );
}

function AccountModal({ account, options, onClose, onSaved }: { account: LedgerAccount | null; options: FinanceOptions; onClose: () => void; onSaved: () => void }) {
  const [code, setCode] = useState(account?.code || '');
  const [description, setDescription] = useState(account?.description || '');
  const [typeId, setTypeId] = useState(String(account?.type_id || ''));
  const [opening, setOpening] = useState(String(account?.opening_balance || 0));
  const [active, setActive] = useState(account?.is_active ?? true);
  const [saving, setSaving] = useState(false);
  const [error, setError] = useState<string | null>(null);

  async function submit(event: React.FormEvent) {
    event.preventDefault();
    setSaving(true);
    setError(null);
    try {
      const payload = { code, description, type_id: Number(typeId), opening_balance: Number(opening || 0), is_active: active };
      if (account) await api.put(`/v1/accounts/${account.id}`, payload);
      else await api.post('/v1/accounts', payload);
      onSaved();
    } catch (submitError) {
      setError(getApiErrorMessage(submitError));
    } finally {
      setSaving(false);
    }
  }

  return <OperationModal title={account ? 'Edit ledger account' : 'New ledger account'} onClose={onClose} width="max-w-xl"><form onSubmit={submit} className="space-y-4 p-6">{error && <OperationNotice type="error">{error}</OperationNotice>}<OperationField label="Account code" required><input value={code} disabled={!!account} onChange={(event) => setCode(event.target.value)} className="w-full rounded-xl border border-slate-200 px-3 py-2.5 disabled:bg-slate-100" /></OperationField><OperationField label="Description" required><input value={description} onChange={(event) => setDescription(event.target.value)} className="w-full rounded-xl border border-slate-200 px-3 py-2.5" /></OperationField><OperationField label="Account type" required><SearchSelect value={typeId} onChange={setTypeId} options={options.account_types.map((type) => ({ value: String(type.id), label: type.name, description: type.category?.name }))} placeholder="Select classification" searchPlaceholder="Search classifications..." className="w-full rounded-xl border border-slate-200 bg-white px-3 py-2.5" /></OperationField><OperationField label="Opening balance"><input type="number" value={opening} onChange={(event) => setOpening(event.target.value)} className="w-full rounded-xl border border-slate-200 px-3 py-2.5" /></OperationField><label className="flex items-center gap-3 rounded-xl bg-slate-50 px-4 py-3 text-sm font-semibold"><input type="checkbox" checked={active} onChange={(event) => setActive(event.target.checked)} /> Active for new transactions</label><OperationActions saving={saving} submitLabel="Save account" onCancel={onClose} disabled={!code || !description || !typeId} /></form></OperationModal>;
}
